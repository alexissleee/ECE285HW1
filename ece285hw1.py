import torch
import torch.nn as nn
import torch.nn.functional as F
import matplotlib.pyplot as plt
import kagglehub
from torch.utils.data import DataLoader
from torchvision import datasets, transforms

class VAE(nn.Module):

    def __init__(self):
        super(VAE, self).__init__()

        # encoder
        in_channels = 1 # xray images are grayscale
        hidden_dims = [32, 64, 128, 256, 512]
        self.latent_dim = 256 # hyperparam, tune

        modules = []

        for h_dim in hidden_dims:
            modules.append(
                nn.Sequential(
                    nn.Conv2d(in_channels, out_channels=h_dim, kernel_size=3, stride=2, padding=1),
                    nn.BatchNorm2d(h_dim),
                    nn.LeakyReLU()
                )
            )
            in_channels = h_dim

        self.encoder = nn.Sequential(*modules)
        self.fc_mu = nn.Linear(hidden_dims[-1] * 16, self.latent_dim)
        self.fc_var = nn.Linear(hidden_dims[-1] * 16, self.latent_dim)

        # decoder
        self.decoder_input = nn.Linear(self.latent_dim, hidden_dims[-1] * 16)
        modules = []
        hidden_dims.reverse()
        for i in range(len(hidden_dims) - 1):
            modules.append(
                nn.Sequential(
                    nn.ConvTranspose2d(
                        hidden_dims[i],
                        hidden_dims[i + 1],
                        kernel_size=3,
                        stride=2,
                        padding=1,
                        output_padding=1
                    ),
                    nn.BatchNorm2d(hidden_dims[i + 1]),
                    nn.LeakyReLU()
                )
            )
        modules.append(
            nn.Sequential(
                nn.ConvTranspose2d(
                    hidden_dims[-1],
                    out_channels=1,
                    kernel_size=3,
                    stride=2,
                    padding=1,
                    output_padding=1
                ),
                nn.Sigmoid()
            )
        )
        self.decoder = nn.Sequential(*modules)

    # forward pass
    def forward(self, img):

        # encoder
        latent = self.encoder(img)
        latent = torch.flatten(latent, start_dim=1)
        mu = self.fc_mu(latent)
        log_var = self.fc_var(latent)

        # reparameterization
        std = torch.exp(0.5 * log_var)
        eps = torch.randn_like(std)
        z = eps * std + mu

        # decoder
        result = self.decoder_input(z)
        result = result.view(-1, 512, 4, 4)
        result = self.decoder(result)

        return result, mu, log_var

# use gpu acceleration
device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

# load model
model = VAE().to(device)

# load data
path = kagglehub.dataset_download("paultimothymooney/chest-xray-pneumonia")

print("Path to dataset files:", path)

transform = transforms.Compose([
    transforms.Grayscale(num_output_channels=1),
    transforms.Resize((128, 128)),
    transforms.ToTensor()
])

train_dataset = datasets.ImageFolder(
    root=f"{path}/chest_xray/train",
    transform=transform
)

test_dataset = datasets.ImageFolder(
    root=f"{path}/chest_xray/test",
    transform=transform
)

val_dataset = datasets.ImageFolder(
    root=f"{path}/chest_xray/val",
    transform=transform
)

train_loader = DataLoader(
    train_dataset,
    batch_size=32,
    shuffle=True
)

test_loader = DataLoader(
    test_dataset,
    batch_size=32,
    shuffle=False
)

val_loader = DataLoader(
    val_dataset,
    batch_size=32,
    shuffle=False
)

optimizer = torch.optim.Adam(
    model.parameters(),
    lr=0.001
)

epochs = 30

# for plots
train_losses = []
val_losses = []

# train loop
for epoch in range(epochs):

    model.train()
    train_loss = 0

    for images, labels in train_loader:

        images = images.to(device)

        # forward pass
        result, mu, log_var = model(images)

        # loss
        recons_loss = F.mse_loss(result, images, reduction="mean")
        kld_loss = -0.5 * torch.mean(torch.sum(1 + log_var - mu.pow(2) - log_var.exp(), dim=1))
        loss = recons_loss + 0.0001 * kld_loss # tested 0.001

        # backprop
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        train_loss += loss.item() * images.size(0)

    train_loss /= len(train_loader.dataset)
    print(f"Epoch {epoch+1}/{epochs} | Loss: {train_loss:.4f}")
    train_losses.append(train_loss)

    # val
    model.eval()
    val_loss = 0

    with torch.no_grad():
        for images, labels in val_loader:

            images = images.to(device)

            result, mu, log_var = model(images)

            recons_loss = F.mse_loss(result, images, reduction="mean")
            kld_loss = -0.5 * torch.mean(torch.sum(
                1 + log_var - mu.pow(2) - log_var.exp(), dim=1
            ))
            loss = recons_loss + 0.0001 * kld_loss

            val_loss += loss.item() * images.size(0)

    val_loss /= len(val_loader.dataset)
    val_losses.append(val_loss)

    print(
        f"Epoch {epoch+1}/{epochs} | "
        f"Train Loss: {train_loss:.4f} | "
        f"Val Loss: {val_loss:.4f}"
    )

# save model checkpoints
