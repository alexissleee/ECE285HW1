from ignite.metrics import FID, InceptionScore
from PIL import Image

def prepare_for_inception(batch):
    processed = []

    for img in batch:
        img = transforms.ToPILImage()(img.cpu())
        img = img.convert("RGB")
        img = img.resize((299, 299), Image.Resampling.BILINEAR)

        img = transforms.ToTensor()(img)
        processed.append(img)

    return torch.stack(processed).to(device)

fid_metric = FID(device=device)
is_metric = InceptionScore(device=device)

model.eval()

fid_metric.reset()
is_metric.reset()

with torch.no_grad():

    for images, labels in test_loader:

        images = images.to(device)
        batch_size = images.size(0)

        z = torch.randn(
            batch_size,
            model.latent_dim,
            device=device
        )

        generated = model.decoder_input(z)
        generated = generated.view(-1, 512, 4, 4)
        generated = model.decoder(generated)

        real_images = prepare_for_inception(images)
        fake_images = prepare_for_inception(generated)

        fid_metric.update((fake_images, real_images))
        is_metric.update(fake_images)

fid_score = fid_metric.compute()
is_score = is_metric.compute()

print("FID:", fid_score)
print("Inception Score:", is_score)